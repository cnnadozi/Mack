export type Translator = {
  t(key: MessageKey, vars?: Record<string, string | number>): string;
  /** BCP 47 code for the lang attribute, so screen readers pronounce the words correctly. */
  lang: string;
  dir: "ltr" | "rtl";
};

/** Mack's words in a language from the settings ("" or unknown means English). */
export function translator(language: string): Translator {
  const name = (readLanguage(language) || "English") as LanguageName;
  const messages = MESSAGES[name];
  return {
    t: (key, vars) =>
      Object.entries(vars ?? {}).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        messages[key] ?? EN[key],
      ),
    lang: CODES[name],
    dir: RTL.has(name) ? "rtl" : "ltr",
  };
}

